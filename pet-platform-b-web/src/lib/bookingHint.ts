/**
 * 代客建单弹窗的提示文案（纯函数，便于单测）。
 *
 * <p>"当天没有可约时段"的原因因服务而异：资源型服务（洗澡/美容/诊疗/托管）多半是台位/诊室/笼位占满；
 * 而遛狗这类**不需要实体资源**的服务（`requiredResourceType` 为空）根本没有台位可占，
 * 空时段只可能来自营业时间/休息/提前量/可预约天数——把原因归到"洗浴台"会把员工引去查一个不存在的资源。
 */
export function emptySlotsHint(requiredResourceType: string | null | undefined): string {
  if (!requiredResourceType) {
    return '当天没有可约时段：不在营业时间（含休息时段）、未满足提前预约要求，或已超出可预约天数。换一天试试。'
  }
  return '当天没有可约时段：该类资源当天已占满（洗澡要洗浴台、诊疗要诊室、托管要笼位），或门店还没登记该类资源台账。可以换一天或换一项服务试试。'
}
